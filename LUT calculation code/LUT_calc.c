#define R1 680.0
#define R2 680.0
#define R5 680.0

#define R3 1e5
#define R6 1e5

#define R4 3.3e5
#define R7 3.3e5

#define Rz2 (1.0 / ((1.0 / R2) + (1.0 / R3) + (1.0 / R5)))

static inline double Rz1(size_t i){
    return (1.0 / ((1.0 / LUT_R[i]) + (1.0 / (R6 + R7))));
}


int main(){

    for(size_t i = 0; i < LUT_SIZE; i++){

        double ADC_raw = 4095.0 * (R4 / R3) * ((Rz1(i) / (R1 + Rz1(i))) - (Rz2 * ((1.0 / R2) + ((R7 * Rz1(i)) / (R3 * (R6 + R7) * (R1 + Rz1(i)))))));

        printf("%.3lf,\t// %d C\n", ADC_raw, LUT_START_TEMP + (int)i * LUT_STEP);

    }

    return 0;

}
