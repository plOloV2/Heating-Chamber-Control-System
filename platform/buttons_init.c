/**
 * @file button_init.c
 * @brief Implementation of button EXTI and 25 ms timer initialization.
 *
 * @author Aleksander Dziągwa
 * @date 12.11.2026
 */

#include "stm32f4xx.h"
#include "GPIO_pins_def.h"
#include "drivers/buttons_operations.h"

/**
 * @brief TIM6 timing constants for 25 ms window
 * @details 10 kHz tick (0.1 ms per tick) -> 250 ticks = 25 ms.
 */
#define TIM6_TICK_HZ            10000UL
#define BUTTON_WINDOW_TICKS     250U


/** @brief Calculate current APB1 Timer clock frequency in Hz based on SystemCoreClock */
static uint32_t get_apb1_timer_clock(void)
{
    extern uint32_t SystemCoreClock;
    extern const uint8_t APBPrescTable[8];

    const uint32_t ppre1_idx = READ_BIT(RCC->CFGR, RCC_CFGR_PPRE1) >> RCC_CFGR_PPRE1_Pos;
    const uint8_t apb1_shift = APBPrescTable[ppre1_idx];
    const uint32_t pclk1 = SystemCoreClock >> apb1_shift;

    /* STM32F4 doubles APB timer clock when APB prescaler is not /1 */
    return (apb1_shift == 0U) ? pclk1 : (pclk1 * 2UL);
}


/** @brief Configure SYSCFG EXTI lines, Rising/Falling interrupts, and TIM6 25 ms timer */
void configure_buttons(void)
{
    /** Enable APB2 clock for SYSCFG and APB1 clock for TIM6. */
    SET_BIT(RCC->APB2ENR, RCC_APB2ENR_SYSCFGEN);
    (void)RCC->APB2ENR;

    SET_BIT(RCC->APB1ENR, RCC_APB1ENR_TIM6EN);
    (void)RCC->APB1ENR;

    /** Route PB0 (EXTI0), PB1 (EXTI1), and PB2 (EXTI2) to Port B in EXTICR[0]. */
    MODIFY_REG(SYSCFG->EXTICR[0],
               SYSCFG_EXTICR1_EXTI0 | SYSCFG_EXTICR1_EXTI1 | SYSCFG_EXTICR1_EXTI2,
               SYSCFG_EXTICR1_EXTI0_PB | SYSCFG_EXTICR1_EXTI1_PB | SYSCFG_EXTICR1_EXTI2_PB);

    /** Route PB10 (EXTI10) to Port B in EXTICR[2]. */
    MODIFY_REG(SYSCFG->EXTICR[2],
               SYSCFG_EXTICR3_EXTI10,
               SYSCFG_EXTICR3_EXTI10_PB);

    /** Configure EXTI lines for both Rising (press) and Falling (release) edges. */
    SET_BIT(EXTI->RTSR, ALL_BUTTONS_MASK);
    SET_BIT(EXTI->FTSR, ALL_BUTTONS_MASK);

    /** Clear any pending flags and unmask button EXTI lines. */
    EXTI->PR = ALL_BUTTONS_MASK;
    SET_BIT(EXTI->IMR, ALL_BUTTONS_MASK);

    /** Configure TIM6 in One-Pulse Mode for 25 ms evaluation window. */
    const uint32_t tim6_clk = get_apb1_timer_clock();
    TIM6->PSC = (uint16_t)((tim6_clk / TIM6_TICK_HZ) - 1UL);
    TIM6->ARR = BUTTON_WINDOW_TICKS - 1U;

    SET_BIT(TIM6->CR1, TIM_CR1_OPM);
    TIM6->EGR = TIM_EGR_UG;     /** Force prescaler update immediately */
    TIM6->SR  = 0U;             /** Clear update flag generated by UG */
    SET_BIT(TIM6->DIER, TIM_DIER_UIE);

    /** Configure NVIC priorities and enable IRQs. */
    NVIC_SetPriority(TIM6_DAC_IRQn, 5U);
    NVIC_EnableIRQ(TIM6_DAC_IRQn);

    NVIC_SetPriority(EXTI0_IRQn, 6U);
    NVIC_SetPriority(EXTI1_IRQn, 6U);
    NVIC_SetPriority(EXTI2_IRQn, 6U);
    NVIC_SetPriority(EXTI15_10_IRQn, 6U);

    NVIC_EnableIRQ(EXTI0_IRQn);
    NVIC_EnableIRQ(EXTI1_IRQn);
    NVIC_EnableIRQ(EXTI2_IRQn);
    NVIC_EnableIRQ(EXTI15_10_IRQn);
}
