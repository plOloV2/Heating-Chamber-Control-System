/**
 * @file timers_init.c
 * @brief Implementation of basic timers (TIM6 and TIM7) initialization.
 *
 * @details Configures TIM6 in One-Pulse Mode for 25 ms button debouncing window,
 *          and TIM7 in continuous periodic mode for a 1-second main-system interrupt.
 *          TIM7 interrupt should have high prority, as main system functions depend on it.
 *
 * @author Aleksander Dziągwa
 * @date 12.11.2026
 */

#include "stm32f4xx.h"

/**
 * @brief Common 10 kHz tick frequency (0.1 ms per tick) for TIM6 and TIM7
 * @details
 * At 84 MHz APB1 Timer Clock: PSC = (84000000 / 10000) - 1 = 8399.
 * At 16 MHz HSI fallback:     PSC = (16000000 / 10000) - 1 = 1599.
 */
#define BASIC_TIM_TICK_HZ       10000UL

/** @brief TIM6: 250 ticks * 0.1 ms = 25 ms one-pulse window */
#define TIM6_WINDOW_TICKS       250U

/** @brief TIM7: 10000 ticks * 0.1 ms = 1000 ms periodic interrupt */
#define TIM7_PERIOD_TICKS       10000U


/** @brief Calculate current APB1 Timer clock frequency in Hz based on SystemCoreClock */
static uint32_t get_apb1_timer_clock(void)
{
    extern uint32_t SystemCoreClock;
    extern const uint8_t APBPrescTable[8];

    const uint32_t ppre1_idx = READ_BIT(RCC->CFGR, RCC_CFGR_PPRE1) >> RCC_CFGR_PPRE1_Pos;
    const uint8_t apb1_shift = APBPrescTable[ppre1_idx];
    const uint32_t pclk1 = SystemCoreClock >> apb1_shift;

    /* STM32F4 hardware doubles APB timer clock when APB prescaler is not /1 */
    return (apb1_shift == 0U) ? pclk1 : (pclk1 * 2UL);
}


/** @brief Configure TIM6 and TIM7  */
void configure_timers(void)
{
    /** Enable APB1 clock for TIM6 and TIM7. */
    SET_BIT(RCC->APB1ENR, RCC_APB1ENR_TIM6EN | RCC_APB1ENR_TIM7EN);
    (void)RCC->APB1ENR;

    const uint32_t tim_clk = get_apb1_timer_clock();
    const uint16_t prescaler = (uint16_t)((tim_clk / BASIC_TIM_TICK_HZ) - 1UL);

    /**
     * Configure TIM6:
     * - 25 ms evaluation window for buttons
     * - One-Pulse Mode (OPM), remains stopped until triggered by EXTI ISR
     */
    TIM6->PSC = prescaler;
    TIM6->ARR = TIM6_WINDOW_TICKS - 1U;
    SET_BIT(TIM6->CR1, TIM_CR1_OPM);
    TIM6->EGR = TIM_EGR_UG;             /** Load prescaler immediately */
    TIM6->SR  = 0U;                     /** Clear UIF generated by UG */
    SET_BIT(TIM6->DIER, TIM_DIER_UIE);

    NVIC_SetPriority(TIM6_DAC_IRQn, 8U);
    NVIC_EnableIRQ(TIM6_DAC_IRQn);

    /**
     * Configure TIM7:
     * - 1 s periodic interrupt
     * - Auto-reload preload enabled (ARPE), starts counting immediately
     */
    TIM7->PSC = prescaler;
    TIM7->ARR = TIM7_PERIOD_TICKS - 1U;
    SET_BIT(TIM7->CR1, TIM_CR1_ARPE);
    TIM7->EGR = TIM_EGR_UG;             /** Load prescaler and ARR immediately */
    TIM7->SR  = 0U;                     /** Clear UIF generated by UG */
    SET_BIT(TIM7->DIER, TIM_DIER_UIE);

    NVIC_SetPriority(TIM7_IRQn, 7U);
    NVIC_EnableIRQ(TIM7_IRQn);

    /** Start TIM7 continuous counter. */
    SET_BIT(TIM7->CR1, TIM_CR1_CEN);
}
